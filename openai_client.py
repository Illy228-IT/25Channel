from openai import OpenAI
from config import OPENAI_API_KEY, MODEL
import random

client = OpenAI(
    api_key=OPENAI_API_KEY
)

POST_STYLES = [
    "аналитический",
    "экспертный",
    "новостной",
    "деловой",
    "премиальный",
    "энергичный"
]

EMOJIS = """
🔥 ⚡ 🚀 💎 🌍 🏆 🎯 💰 🤖 📈 📰 🌟 🔔 💡
🌐 📊 📣 💥 🚨 ⭐ 📌 🧠 💼 🛠️
🥷 😍 🥰 🤩 🥳 😱 😡 🤯 😈 🐳 🍀 ❤️ 📱
"""


def generate_post(prompt: str):

    style = random.choice(POST_STYLES)

    response = client.chat.completions.create(
        model=MODEL,
        messages=[
            {
                "role": "system",
                "content": prompt
            },
            {
                "role": "user",
                "content": f"""
Создай КРУТОЙ Telegram-пост.

Стиль: {style}

Используй только HTML Telegram.

Разрешено:

<b>жирный текст</b>

<i>курсив</i>

Используй эмодзи:

{EMOJIS}

КРИТИЧЕСКИ ВАЖНО:

Заголовок должен содержать случайный эмодзи.

Не начинай большинство постов с 🚀.

Запрещено использовать 🚀 чаще одного раза за пост.

Чередуй эмодзи между абзацами.

Используй разные эмодзи для разных тем:

💰 📈 🤖 — финансы и технологии

🌍 🌐 📣 — мировые события

🧠 💡 📌 — идеи и образование

🚨 ⚡ 🔥 — срочные новости

🏆 🎯 💎 — достижения и успех

Каждый абзац желательно начинать с разного эмодзи.

Минимум 6 разных эмодзи на пост.

Минимум 5 выделений через <b>.

Минимум 2 выделения через <i>.

Не повторять один и тот же эмодзи подряд.

Абзацы короткие.

Максимум 2 предложения в абзаце.

НЕ ИСПОЛЬЗОВАТЬ:

Что произошло:
Почему это важно:
Возможные последствия:
Вывод:
Главное:
Итоги:

🚀 в начале каждого поста

одинаковые заголовки

одинаковые эмодзи в каждом посте

одинаковую структуру текста

❌ Не писать как статья.

❌ Не писать как журналист.

❌ Не писать как новостной сайт.

Пиши как владелец популярного Telegram-канала.

Используй:

- эмоции
- интригу
- интересные факты
- яркие формулировки
- мнение автора

Размер:

500-900 символов.

3-6 абзацев.

В конце отдельной строкой добавляй хештеги.

Пост должен выглядеть дорого, живо и современно.

Каждый пост должен визуально отличаться от предыдущего.
"""
            }
        ]
    )

    return response.choices[0].message.content


